namespace CruceChaos.Core.Cards
{
    /// <summary>
    /// The four suits of the Cruce deck. These are the project's renamed
    /// versions of the traditional Hungarian-deck suits:
    ///   Green  = Verde  (toamna / autumn)
    ///   Red    = Roșu   (primăvara / spring)
    ///   Acorn  = Ghindă (iarna / winter)
    ///   Bell   = Dubă   (vara / summer)
    /// </summary>
    public enum Suit
    {
        Green,
        Red,
        Acorn,
        Bell
    }
}
